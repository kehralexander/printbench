import { describe, expect, it } from 'vitest'
import { parseGcodeDetails } from './gcode-details'

// Inline comment blocks in each slicer's shape; see gcode-metadata.test.ts.

const PRUSA_TAIL = `
; filament used [mm] = 1000.5, 250.25
; filament used [cm3] = 2.4, 0.6
; filament used [g] = 3.0, 0.75
; total filament used for wipe tower [g] = 1.23
; estimated printing time (normal mode) = 1h 23m 4s
; estimated printing time (silent mode) = 1h 30m 0s
; estimated first layer printing time (normal mode) = 2m 10s
; prusaslicer_config = begin
; bed_shape = 0x-4,250x-4,250x210,0x210
; filament_density = 1.24;1.27
; filament_diameter = 1.75,1.75
; gcode_flavor = marlin2
; max_print_height = 220
; printer_model = MK4S
; printer_settings_id = Original Prusa MK4S 0.4 nozzle
; prusaslicer_config = end
`

const ORCA_HEAD = `; HEADER_BLOCK_START
; generated by OrcaSlicer 2.1.1 on 2024-06-01 at 10:00:00
; model printing time: 22m 25s; total estimated time: 28m 23s
; total layer number: 66
; total filament length [mm] : 1234.56
; total filament volume [cm^3] : 2963.12
; total filament weight [g] : 3.73
; max_z_height: 13.20
; HEADER_BLOCK_END
`

const ORCA_TAIL = `
; CONFIG_BLOCK_START
; gcode_flavor = klipper
; printable_area = 0x0,256x0,256x256,0x256
; printable_height = 250
; printer_model = Bambu Lab X1 Carbon
; CONFIG_BLOCK_END
`

const CURA_HEAD = `;FLAVOR:Marlin
;TIME:3723
;Filament used: 4.12345m
;Layer height: 0.2
;MINX:85.5
;MINY:90
;MINZ:0.2
;MAXX:150.25
;MAXY:120
;MAXZ:20.4
;TARGET_MACHINE.NAME:Ultimaker S5
;LAYER_COUNT:102
;Generated with Cura_SteamEngine 5.7.0
`

describe('parseGcodeDetails', () => {
  it('reads PrusaSlicer summary and machine figures', () => {
    expect(parseGcodeDetails('', PRUSA_TAIL)).toEqual({
      filamentLengthMm: 1250.75,
      filamentLengthsMm: [1000.5, 250.25],
      filamentVolumeCm3: 3,
      filamentDiametersMm: [1.75, 1.75],
      filamentDensities: [1.24, 1.27],
      wipeTowerG: 1.23,
      silentDurationMin: 90,
      firstLayerDurationMin: 2,
      printerModel: 'MK4S',
      printerPreset: 'Original Prusa MK4S 0.4 nozzle',
      bed: { minX: 0, minY: -4, maxX: 250, maxY: 210 },
      printableHeightMm: 220,
      gcodeFlavor: 'marlin2',
    })
  })

  it('reads the Orca header block, both times off its one line', () => {
    expect(parseGcodeDetails(ORCA_HEAD, ORCA_TAIL)).toEqual({
      layerCount: 66,
      maxZMm: 13.2,
      filamentLengthMm: 1234.56,
      filamentVolumeCm3: 2963.12,
      modelDurationMin: 22,
      totalDurationMin: 28,
      printerModel: 'Bambu Lab X1 Carbon',
      bed: { minX: 0, minY: 0, maxX: 256, maxY: 256 },
      printableHeightMm: 250,
      gcodeFlavor: 'klipper',
    })
  })

  it('reads the Cura header, converting metres of filament', () => {
    expect(parseGcodeDetails(CURA_HEAD, CURA_HEAD)).toEqual({
      layerCount: 102,
      maxZMm: 20.4,
      filamentLengthMm: 4123.45,
      printerPreset: 'Ultimaker S5',
      gcodeFlavor: 'marlin',
      extents: { minX: 85.5, minY: 90, minZ: 0.2, maxX: 150.25, maxY: 120, maxZ: 20.4 },
    })
  })

  it('drops values that do not read rather than guessing', () => {
    const tail = `
; bed_shape = nonsense
; filament used [mm] = 12, abc
; printer_model = undefine
; max_print_height = -5
`
    expect(parseGcodeDetails('', tail)).toEqual({})
  })

  it('reads nothing from binary G-code', () => {
    expect(parseGcodeDetails('GCDE\u0001\u0000', PRUSA_TAIL)).toEqual({})
  })
})
