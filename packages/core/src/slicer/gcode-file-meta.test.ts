import { describe, expect, it } from 'vitest'
import { buildSlicerFileMeta } from './gcode-file-meta'
import { scanGcodeBody } from './gcode-body-scan'

const HEAD = `; generated by OrcaSlicer 2.1.1 on 2024-06-01 at 10:00:00
; model printing time: 50m; total estimated time: 1h 40m
; total layer number: 2
; max_z_height: 0.6
`

const TAIL = `
; filament used [g] = 3.0, 0.0, 1.5
; total filament cost = 0.42
; filament_type = PLA;PLA;PETG
; filament_colour = #FF0000;#00FF00;#0000FF
; filament_diameter = 1.75,1.75,1.75
; filament_density = 1.24,1.24,1.27
; layer_height = 0.2
; printable_area = 0x0,256x0,256x256,0x256
`

const BODY = `M83
M73 P0
T0
;LAYER_CHANGE
;Z:0.2
G1 X10 Y10 Z0.2
G1 X20 Y10 E1
M73 P50
T2
;TYPE:Prime tower
G1 X200 Y200 E10
;TYPE:Outer wall
M600
G1 X20 Y20 Z0.4 E1
`

describe('buildSlicerFileMeta', () => {
  it('leaves out the slicer’s own cost', () => {
    const meta = buildSlicerFileMeta(HEAD, TAIL, null)
    expect(meta).not.toHaveProperty('filamentCost')
    expect(meta.material).toBe('PLA')
    expect(meta.totalDurationMin).toBe(100)
  })

  it('reads only the ends when there is no body scan', () => {
    const meta = buildSlicerFileMeta(HEAD, TAIL, null)
    expect(meta.body).toBeUndefined()
    expect(meta.layerCount).toBe(2)
    // Grams say which tools print, until the body says otherwise.
    expect(meta.filaments?.map((tool) => tool.used)).toEqual([true, false, true])
  })

  it('combines the body scan with the header', () => {
    const meta = buildSlicerFileMeta(HEAD, TAIL, scanGcodeBody(BODY))

    // The slicer's layer count stands; the measured height replaces its summary.
    expect(meta.layerCount).toBe(2)
    expect(meta.maxZMm).toBe(0.4)
    expect(meta.extents).toEqual({
      minX: 10,
      minY: 10,
      minZ: 0.2,
      maxX: 200,
      maxY: 200,
      maxZ: 0.4,
    })
    expect(meta.filaments?.map((tool) => tool.used)).toEqual([true, false, true])

    // 10 mm of 1.75 mm filament at 1.27 g/cm³.
    expect(meta.purge).toEqual([{ tool: 2, mm: 10, grams: 0.03 }])
    expect(meta.purgeG).toBe(0.03)

    // M73 P without R: placed by percentage of the total estimate.
    expect(meta.body?.pauses).toMatchObject([
      { command: 'M600', progressPercent: 50, elapsedMin: 50, tool: 2 },
    ])
    expect(meta.body?.toolChangeTimeline).toMatchObject([{ from: 0, to: 2, elapsedMin: 50 }])
  })

  it('prefers Prusa’s own wipe tower grams', () => {
    const tail = `${TAIL}; total filament used for wipe tower [g] = 2.5\n`
    expect(buildSlicerFileMeta(HEAD, tail, scanGcodeBody(BODY)).purgeG).toBe(2.5)
  })

  it('leaves purge grams out without a density to convert with', () => {
    const tail = TAIL.replace(/; filament_density.*\n/, '')
    const meta = buildSlicerFileMeta(HEAD, tail, scanGcodeBody(BODY))
    expect(meta.purge).toEqual([{ tool: 2, mm: 10, grams: null }])
    expect(meta.purgeG).toBeUndefined()
  })
})
