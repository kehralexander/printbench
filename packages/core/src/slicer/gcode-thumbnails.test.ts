import { describe, expect, it } from 'vitest'
import { extractSlicerThumbnails } from './gcode-thumbnails'

const PNG = Buffer.from([137, 80, 78, 71, 13, 10, 26, 10, 1, 2, 3, 4])
const JPEG = Buffer.from([255, 216, 255, 224, 9, 9])

function commentBlock(label: string, data: Buffer, width = 8): string[] {
  const encoded = data.toString('base64')
  const lines = [`; ${label} begin 16x16 ${encoded.length}`]
  for (let i = 0; i < encoded.length; i += width) lines.push(`; ${encoded.slice(i, i + width)}`)
  lines.push(`; ${label} end`)
  return lines
}

function text(lines: string[]): Uint8Array {
  return Buffer.from(lines.join('\n'))
}

describe('extractSlicerThumbnails (text G-code)', () => {
  it('reads PrusaSlicer/Orca PNG and JPG blocks, skipping QOI', () => {
    const result = extractSlicerThumbnails(
      text([
        '; generated by PrusaSlicer 2.8.0',
        '',
        ...commentBlock('thumbnail', PNG),
        ...commentBlock('thumbnail_QOI', Buffer.from('qoifdata')),
        ...commentBlock('thumbnail_JPG', JPEG),
        'G28',
      ]),
    )
    expect(result.map((t) => t.contentType)).toEqual(['image/png', 'image/jpeg'])
    expect(Buffer.from(result[0]!.data)).toEqual(PNG)
  })

  it('handles CRLF line endings', () => {
    const result = extractSlicerThumbnails(Buffer.from(commentBlock('thumbnail', PNG).join('\r\n')))
    expect(result).toHaveLength(1)
  })

  it('drops a block cut off by the read window', () => {
    const lines = commentBlock('thumbnail', PNG)
    expect(extractSlicerThumbnails(text(lines.slice(0, -1)))).toEqual([])
  })

  it('drops a block whose bytes are not an image', () => {
    expect(extractSlicerThumbnails(text(commentBlock('thumbnail', Buffer.from('nope'))))).toEqual(
      [],
    )
  })

  it('returns nothing for G-code without thumbnails', () => {
    expect(extractSlicerThumbnails(text(['G28', 'G1 X0 Y0']))).toEqual([])
  })
})

describe('extractSlicerThumbnails (binary G-code)', () => {
  function header(checksumType: number): Buffer {
    const b = Buffer.alloc(10)
    b.write('GCDE', 0, 'latin1')
    b.writeUInt32LE(1, 4)
    b.writeUInt16LE(checksumType, 8)
    return b
  }

  function block(type: number, payload: Buffer, checksum: boolean): Buffer {
    const head = Buffer.alloc(8)
    head.writeUInt16LE(type, 0)
    head.writeUInt16LE(0, 2)
    head.writeUInt32LE(payload.length, 4)
    const params = Buffer.alloc(type === 5 ? 6 : 2)
    return Buffer.concat([head, params, payload, checksum ? Buffer.alloc(4) : Buffer.alloc(0)])
  }

  it('reads thumbnail blocks before the first G-code block', () => {
    for (const checksum of [false, true]) {
      const file = Buffer.concat([
        header(checksum ? 1 : 0),
        block(0, Buffer.from('Producer=PrusaSlicer'), checksum),
        block(3, Buffer.from('printer_model=MK4'), checksum),
        block(5, PNG, checksum),
        block(5, JPEG, checksum),
        block(1, Buffer.from('G28'), checksum),
        block(5, PNG, checksum),
      ])
      expect(extractSlicerThumbnails(file).map((t) => t.contentType)).toEqual([
        'image/png',
        'image/jpeg',
      ])
    }
  })

  it('stops at a block truncated by the read window', () => {
    const file = Buffer.concat([header(0), block(5, PNG, false)])
    expect(extractSlicerThumbnails(file.subarray(0, file.length - 2))).toEqual([])
  })
})
