import { afterAll, beforeAll, beforeEach, describe, expect, it } from 'vitest'
import { mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { sql } from 'drizzle-orm'
import { createDb } from '@pb/db'
import {
  BillingError,
  addPayment,
  balances,
  createCustomer,
  createInvoice,
  deletePayment,
  invoicePdf,
  modelPriceEstimate,
  priceRequest,
  quoteRequest,
  respondToQuote,
  setPriceStatus,
} from './billing-service'
import { getPrintUsage } from './filament-service'
import { DEFAULT_PRICING, type PricingSettings } from './pricing'
import {
  createRequest,
  getRequest,
  linkRequest,
  requestShareToken,
  setRequestStatus,
  updateRequest,
} from './request-service'

/**
 * Multi-filament requests and charging for them, against a real database:
 * a two-colour G-code numbered and weighed into filament rows, a quote that
 * stays frozen, payments, balances and gap-free invoice numbers.
 */

const LIB = 'b111a000-0000-4000-8000-000000000001'
const MODEL = 'b111a000-0000-4000-8000-000000000002'
const USER = 'billing-test-user'

const pricing: PricingSettings = {
  ...DEFAULT_PRICING,
  enabled: true,
  defaultPerKg: { '*': 20 },
  kwhPrice: 0,
  defaultWatts: null,
  defaultHourlyRate: null,
  defaultSuccessRate: 1,
  roundTo: 0,
  tiers: [
    { key: 'cost', label: 'At cost', markupPercent: 0, handlingFee: 0, minimum: null },
    { key: 'public', label: 'Standard', markupPercent: 50, handlingFee: 2, minimum: null },
  ],
  defaultTier: 'cost',
}

/** Orca-style: two tools, both used, with per-tool grams. */
const TWO_COLOUR = [
  '; generated by OrcaSlicer 2.1.0',
  'G28',
  'T0',
  'G1 X1',
  'T1',
  'G1 X2',
  '; estimated printing time (normal mode) = 1h',
  '; filament used [g] = 40.00, 10.00',
  '; filament_colour = #FF0000;#0000FF',
  '; filament_type = PLA;PETG',
].join('\n')

describe('multi-filament requests and pricing', { tags: ['integration'] }, () => {
  let pool: ReturnType<typeof createDb>['pool']
  let db: ReturnType<typeof createDb>['db']
  let root = ''
  let plateId = ''
  let stlId = ''

  beforeAll(async () => {
    ;({ pool, db } = createDb())
    await cleanup()
    root = await mkdtemp(path.join(tmpdir(), 'pb-billing-'))
    await db.execute(sql`
      INSERT INTO "user" (id, name, email, email_verified)
      VALUES (${USER}, 'Billing Tester', 'billing-tester@example.test', true)`)
    await db.execute(sql`
      INSERT INTO libraries (id, name, kind, backend, path)
      VALUES (${LIB}, 'Billing', 'managed', 'local', ${root})`)
    await db.execute(sql`
      INSERT INTO models (id, library_id, path, name, slug, public_id)
      VALUES (${MODEL}, ${LIB}, 'Sign', 'Two Colour Sign', 'sign', 'billing-sign')`)
    await mkdir(path.join(root, 'Sign'), { recursive: true })
    for (const [filename, content] of [
      ['sign.gcode', TWO_COLOUR],
      ['sign.stl', 'solid'],
    ] as const) {
      await writeFile(path.join(root, 'Sign', filename), content)
      const extension = filename.split('.').pop()!
      const row = await db.execute<{ id: string }>(sql`
        INSERT INTO model_files (model_id, filename, extension, category, size)
        VALUES (${MODEL}, ${filename}, ${extension}, ${extension === 'gcode' ? 'slicer' : 'model'},
                ${Buffer.byteLength(content)})
        RETURNING id`)
      if (extension === 'gcode') plateId = row.rows[0]!.id
      else stlId = row.rows[0]!.id
    }
  })

  beforeEach(async () => {
    await db.execute(sql`DELETE FROM print_requests`)
    await db.execute(sql`DELETE FROM invoices`)
    await db.execute(sql`DELETE FROM customers`)
    await db.execute(sql`DELETE FROM print_runs WHERE model_id = ${MODEL}`)
  })

  afterAll(async () => {
    await cleanup()
    if (root) await rm(root, { recursive: true, force: true })
    await pool.end()
  })

  async function cleanup() {
    await db.execute(sql`DELETE FROM print_requests`)
    await db.execute(sql`DELETE FROM invoices`)
    await db.execute(sql`DELETE FROM customers`)
    await db.execute(sql`DELETE FROM print_runs WHERE model_id = ${MODEL}`)
    await db.execute(sql`DELETE FROM filament_stock_changes WHERE reason LIKE 'billing-test%'`)
    await db.execute(sql`DELETE FROM libraries WHERE id = ${LIB}`)
    await db.execute(sql`DELETE FROM "user" WHERE id = ${USER}`)
  }

  const signRequest = (extra: Parameters<typeof createRequest>[1] | object = {}) =>
    createRequest(
      db,
      { title: 'Sign', modelId: MODEL, modelFileId: plateId, ...extra } as Parameters<
        typeof createRequest
      >[1],
      USER,
    )

  describe('filaments from the G-code', () => {
    it('numbers and weighs one row per tool the file uses', async () => {
      const { id } = await signRequest()
      const request = await getRequest(db, id)
      expect(request?.filaments).toEqual([
        expect.objectContaining({ tool: 0, material: 'PLA', colorHex: '#ff0000', grams: 40 }),
        expect.objectContaining({ tool: 1, material: 'PETG', colorHex: '#0000ff', grams: 10 }),
      ])
      expect(request?.filamentG).toBe(50)
    })

    it('keeps what was asked for per tool, and turns the rows back into wishes off the file', async () => {
      const { id } = await signRequest({
        filaments: [{ material: 'PLA', colorHex: '#ffffff' }, { spoolmanSpoolId: 4 }],
      })
      expect((await getRequest(db, id))?.filaments).toEqual([
        expect.objectContaining({ tool: 0, colorHex: '#ffffff', grams: 40 }),
        expect.objectContaining({ tool: 1, spoolmanSpoolId: 4, grams: 10 }),
      ])

      await linkRequest(db, id, MODEL, stlId)
      expect((await getRequest(db, id))?.filaments).toEqual([
        expect.objectContaining({ tool: null, colorHex: '#ffffff', grams: null }),
        expect.objectContaining({ tool: null, spoolmanSpoolId: 4, grams: null }),
      ])
    })

    it('records spool usage per filament when marked printed, and withdraws it on reopening', async () => {
      const filament = await db.execute<{ id: string }>(sql`
        INSERT INTO filaments (name, material) VALUES ('Red', 'PLA') RETURNING id`)
      const spool = await db.execute<{ id: string }>(sql`
        INSERT INTO filament_spools (filament_id, purchase_cost, nominal_weight_g)
        VALUES (${filament.rows[0]!.id}, 20, 1000) RETURNING id`)
      const spoolId = spool.rows[0]!.id
      try {
        const { id } = await signRequest({ quantity: 2 })
        const rows = (await getRequest(db, id))!.filaments
        await updateRequest(db, id, {
          filaments: rows.map((row) => (row.tool === 0 ? { ...row, spoolId } : row)),
        })
        await setRequestStatus(db, id, 'done', { userId: USER })
        const runId = (await getRequest(db, id))!.printRunId!
        expect((await getPrintUsage(db, [runId])).get(runId)).toEqual([
          expect.objectContaining({ spoolId, grams: 80, costPerGram: 0.02 }),
        ])

        // Untouched since the queue wrote it, so reopening takes it back.
        await setRequestStatus(db, id, 'requested')
        const left = await db.execute(sql`SELECT 1 FROM print_runs WHERE id = ${runId}`)
        expect(left.rows).toHaveLength(0)
      } finally {
        await db.execute(sql`DELETE FROM print_requests`)
        await db.execute(sql`DELETE FROM filament_stock_changes WHERE spool_id = ${spoolId}`)
        await db.execute(sql`DELETE FROM filament_spools WHERE id = ${spoolId}`)
        await db.execute(sql`DELETE FROM filaments WHERE id = ${filament.rows[0]!.id}`)
      }
    })
  })

  describe('quotes', () => {
    it('prices every filament and freezes the quote until something changes', async () => {
      const { id } = await signRequest({ quantity: 2, pricingTier: 'public' })
      const quote = await quoteRequest(db, id, pricing)
      // 50 g × 0.02 = 1.00 a copy, × 2 + 2 handling = 4.00, × 1.5 = 6.00
      expect(quote.price).toBe(6)
      expect(await getRequest(db, id)).toMatchObject({
        priceStatus: 'quoted',
        quotedPrice: 6,
        quotedCost: 2,
        needsRequote: false,
      })

      await updateRequest(db, id, { quantity: 3 })
      expect(await getRequest(db, id)).toMatchObject({ quotedPrice: 6, needsRequote: true })

      // The title is not something the price depends on.
      await quoteRequest(db, id, pricing)
      await updateRequest(db, id, { title: 'Door sign', quantity: 3 })
      expect((await getRequest(db, id))?.needsRequote).toBe(false)
    })

    it('keeps a typed price as typed', async () => {
      const { id } = await signRequest()
      await quoteRequest(db, id, pricing, { manualPrice: 12.5 })
      const request = await getRequest(db, id)
      expect(request).toMatchObject({ quotedPrice: 12.5, priceManual: true })
      const split = request!.quoteBreakdown!.reduce((sum, line) => sum + line.amount, 0)
      expect(Math.round(split * 100) / 100).toBe(12.5)
    })

    it('takes the customer tier when the request has none', async () => {
      await createCustomer(db, { name: 'Tom', defaultTier: 'public' })
      const { id } = await signRequest({ requestedBy: 'tom' })
      const request = await getRequest(db, id)
      expect(request?.customerName).toBe('Tom')
      expect((await priceRequest(db, request!, pricing)).tier.key).toBe('public')
    })

    it('lets the requester accept a standing quote from their link, and only that', async () => {
      const { id } = await signRequest()
      const token = await requestShareToken(db, id)
      await expect(respondToQuote(db, token, 'accept')).rejects.toBeInstanceOf(BillingError)

      await quoteRequest(db, id, pricing)
      await respondToQuote(db, token, 'accept')
      expect(await getRequest(db, id)).toMatchObject({ priceStatus: 'accepted' })
      expect((await getRequest(db, id))?.acceptedAt).toBeInstanceOf(Date)

      // Expired quotes cannot be accepted.
      await quoteRequest(db, id, pricing)
      await db.execute(
        sql`UPDATE print_requests SET quote_expires_at = now() - interval '1 day' WHERE id = ${id}`,
      )
      await expect(respondToQuote(db, token, 'decline')).rejects.toBeInstanceOf(BillingError)
    })

    it('refuses steps the price cannot take', async () => {
      const { id } = await signRequest()
      await expect(setPriceStatus(db, id, 'accepted')).rejects.toBeInstanceOf(BillingError)
      await setPriceStatus(db, id, 'waived')
      expect((await getRequest(db, id))?.priceStatus).toBe('waived')
    })
  })

  describe('payments, balances and invoices', () => {
    it('marks a request paid once payments cover it, and back when one is taken away', async () => {
      const { id } = await signRequest()
      await quoteRequest(db, id, pricing)
      await setPriceStatus(db, id, 'accepted')
      await addPayment(db, id, { amount: 0.4, method: 'cash' })
      expect((await getRequest(db, id))?.priceStatus).toBe('accepted')
      const second = await addPayment(db, id, { amount: 0.6, method: 'paypal' })
      expect(await getRequest(db, id)).toMatchObject({ priceStatus: 'paid', paid: 1 })
      await deletePayment(db, second)
      expect(await getRequest(db, id)).toMatchObject({ priceStatus: 'accepted', paid: 0.4 })
    })

    it('adds up what each customer owes, Tom and tom as one', async () => {
      await createCustomer(db, { name: 'Tom' })
      for (const name of ['Tom', 'tom']) {
        const { id } = await signRequest({ requestedBy: name })
        await quoteRequest(db, id, pricing)
        await setPriceStatus(db, id, 'accepted')
      }
      const { id: once } = await signRequest({ requestedBy: 'Ann' })
      await quoteRequest(db, once, pricing)
      await setPriceStatus(db, once, 'accepted')
      await addPayment(db, once, { amount: 0.25 })

      const list = await balances(db)
      expect(list.map((b) => [b.name, b.owed, b.paid, b.balance])).toEqual([
        ['Tom', 2, 0, 2],
        ['Ann', 1, 0.25, 0.75],
      ])
    })

    it('numbers invoices without gaps, one customer each, and renders a PDF', async () => {
      const ids: string[] = []
      for (const name of ['Tom', 'Tom', 'Ann']) {
        const { id } = await signRequest({ requestedBy: name })
        await quoteRequest(db, id, pricing)
        await setPriceStatus(db, id, 'accepted')
        ids.push(id)
      }
      await expect(createInvoice(db, { requestIds: ids }, pricing)).rejects.toBeInstanceOf(
        BillingError,
      )
      const first = await createInvoice(db, { requestIds: ids.slice(0, 2) }, pricing)
      const second = await createInvoice(db, { requestIds: [ids[2]!] }, pricing)
      expect(second.number).toBe(first.number + 1)
      expect(first).toMatchObject({ recipient: 'Tom', total: 2 })
      expect((await getRequest(db, ids[0]!))?.priceStatus).toBe('invoiced')
      await expect(createInvoice(db, { requestIds: [ids[0]!] }, pricing)).rejects.toBeInstanceOf(
        BillingError,
      )

      const pdf = Buffer.from(
        invoicePdf(first, { name: 'Printer Person', address: 'Somewhere 1', paymentNote: '' }, 0.5),
      ).toString('latin1')
      expect(pdf.startsWith('%PDF-1.4')).toBe(true)
      expect(pdf).toContain(`(No. ${first.number})`)
      expect(pdf.trimEnd().endsWith('%%EOF')).toBe(true)
    })

    it('estimates a price for a model from its sliced file', async () => {
      expect(await modelPriceEstimate(db, MODEL, pricing)).toMatchObject({ min: 1, max: 1 })
      expect(await modelPriceEstimate(db, MODEL, { ...pricing, enabled: false })).toBeNull()
    })
  })
})
