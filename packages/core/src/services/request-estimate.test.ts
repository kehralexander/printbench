import { afterAll, beforeAll, beforeEach, describe, expect, it } from 'vitest'
import { mkdtemp, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { sql } from 'drizzle-orm'
import { createDb } from '@pb/db'
import { listPrints } from './print-service'
import {
  createRequest,
  getRequest,
  linkRequest,
  queueStats,
  setRequestStatus,
  suggestEstimate,
  updateRequest,
} from './request-service'

/**
 * Estimated print times and the start time behind "done around".
 *
 * The rule under test above all: a suggestion fills an empty estimate and
 * never replaces one somebody chose — including an explicit "none".
 */

const LIB = '7dab0000-0000-4000-8000-000000000001'
const PLATES = '7dab0000-0000-4000-8000-000000000002'
const SINGLE = '7dab0000-0000-4000-8000-000000000003'
const BARE = '7dab0000-0000-4000-8000-000000000004'
const USER = 'request-estimate-user'

const gcode = (time: string, grams = 12.3) =>
  [
    '; generated by PrusaSlicer',
    'G28',
    `; estimated printing time (normal mode) = ${time}`,
    `; total filament used [g] = ${grams}`,
  ].join('\n')

describe('print time estimates', { tags: ['integration'] }, () => {
  let pool: ReturnType<typeof createDb>['pool']
  let db: ReturnType<typeof createDb>['db']
  let root = ''
  const files: Record<string, string> = {}

  beforeAll(async () => {
    ;({ pool, db } = createDb())
    await cleanup()
    root = await mkdtemp(path.join(tmpdir(), 'pb-estimate-'))

    await db.execute(sql`
      INSERT INTO "user" (id, name, email, email_verified)
      VALUES (${USER}, 'Estimate Tester', 'estimate-tester@example.test', true)`)
    await db.execute(sql`
      INSERT INTO libraries (id, name, kind, backend, path)
      VALUES (${LIB}, 'Estimates', 'managed', 'local', ${root})`)

    for (const [id, dir, name] of [
      [PLATES, 'Plates', 'Plated Model'],
      [SINGLE, 'Single', 'Single Plate'],
      [BARE, 'Bare', 'Bare Mesh'],
    ] as const) {
      await db.execute(sql`
        INSERT INTO models (id, library_id, path, name, slug, public_id)
        VALUES (${id}, ${LIB}, ${dir}, ${name}, ${dir.toLowerCase()}, ${'est-' + dir.toLowerCase()})`)
    }

    const add = async (modelId: string, dir: string, filename: string, content: string) => {
      const { mkdir } = await import('node:fs/promises')
      await mkdir(path.join(root, dir), { recursive: true })
      await writeFile(path.join(root, dir, filename), content)
      const extension = filename.split('.').pop()!
      const row = await db.execute<{ id: string }>(sql`
        INSERT INTO model_files (model_id, filename, extension, category, size)
        VALUES (${modelId}, ${filename}, ${extension},
                ${extension === 'gcode' ? 'slicer' : 'model'}, ${Buffer.byteLength(content)})
        RETURNING id`)
      files[`${dir}/${filename}`] = row.rows[0]!.id
    }
    await add(PLATES, 'Plates', 'plate1.gcode', gcode('1h 23m 4s'))
    await add(PLATES, 'Plates', 'plate2.gcode', gcode('3h 5m'))
    await add(PLATES, 'Plates', 'body.stl', 'solid')
    await add(SINGLE, 'Single', 'only.gcode', gcode('45m 10s'))
    await add(BARE, 'Bare', 'bare.stl', 'solid')
  })

  beforeEach(async () => {
    await db.execute(sql`DELETE FROM print_requests`)
    await db.execute(sql`DELETE FROM print_runs WHERE model_id IN (${PLATES}, ${SINGLE}, ${BARE})`)
  })

  afterAll(async () => {
    await cleanup()
    if (root) await rm(root, { recursive: true, force: true })
    await pool.end()
  })

  async function cleanup() {
    await db.execute(sql`DELETE FROM print_requests`)
    await db.execute(sql`DELETE FROM print_runs WHERE model_id IN (${PLATES}, ${SINGLE}, ${BARE})`)
    await db.execute(sql`DELETE FROM libraries WHERE id = ${LIB}`)
    await db.execute(sql`DELETE FROM "user" WHERE id = ${USER}`)
  }

  async function printed(modelId: string, minutes: number, modelFileId: string | null = null) {
    await db.execute(sql`
      INSERT INTO print_runs (model_id, model_file_id, status, duration_min, finished_at)
      VALUES (${modelId}, ${modelFileId}, 'success', ${minutes}, now())`)
  }

  describe('suggestions', () => {
    it("takes the chosen plate's slicer estimate", async () => {
      expect(await suggestEstimate(db, PLATES, files['Plates/plate2.gcode']!)).toEqual({
        minutes: 185,
        source: 'gcode',
      })
    })

    it("uses a model's only G-code when no file was chosen", async () => {
      expect(await suggestEstimate(db, SINGLE)).toEqual({ minutes: 45, source: 'gcode' })
    })

    it('does not guess between several plates', async () => {
      expect(await suggestEstimate(db, PLATES)).toBeNull()
    })

    it('falls back to the median of earlier prints, preferring the same file', async () => {
      const body = files['Plates/body.stl']!
      await printed(PLATES, 100)
      await printed(PLATES, 200)
      await printed(PLATES, 900)
      expect(await suggestEstimate(db, PLATES)).toEqual({ minutes: 200, source: 'history' })

      await printed(PLATES, 60, body)
      expect(await suggestEstimate(db, PLATES, body)).toEqual({ minutes: 60, source: 'history' })
    })

    it('has nothing to say about a model with no G-code and no history', async () => {
      expect(await suggestEstimate(db, BARE)).toBeNull()
    })
  })

  describe('filling requests', () => {
    it('fills an estimate on creation when none was given', async () => {
      const { id } = await createRequest(
        db,
        { title: 'Plate', modelId: PLATES, modelFileId: files['Plates/plate1.gcode']! },
        USER,
      )
      expect((await getRequest(db, id))?.estimatedMin).toBe(83)
    })

    it('keeps a typed estimate and an explicit "none"', async () => {
      const typed = await createRequest(
        db,
        { title: 'Plate', modelId: SINGLE, estimatedMin: 90 },
        USER,
      )
      const none = await createRequest(
        db,
        { title: 'Plate', modelId: SINGLE, estimatedMin: null },
        USER,
      )
      expect((await getRequest(db, typed.id))?.estimatedMin).toBe(90)
      expect((await getRequest(db, none.id))?.estimatedMin).toBeNull()
    })

    it('fills an empty estimate when linked later, and only then', async () => {
      const empty = await createRequest(db, { title: 'Something' }, USER)
      await linkRequest(db, empty.id, SINGLE)
      expect((await getRequest(db, empty.id))?.estimatedMin).toBe(45)

      const typed = await createRequest(db, { title: 'Other', estimatedMin: 10 }, USER)
      await linkRequest(db, typed.id, SINGLE)
      expect((await getRequest(db, typed.id))?.estimatedMin).toBe(10)
    })

    it('reads grams per print from the G-code and follows the chosen file', async () => {
      const { id } = await createRequest(
        db,
        { title: 'Plate', modelId: PLATES, modelFileId: files['Plates/plate1.gcode']! },
        USER,
      )
      expect((await getRequest(db, id))?.filamentG).toBe(13)

      await linkRequest(db, id, PLATES, files['Plates/body.stl']!)
      expect((await getRequest(db, id))?.filamentG).toBeNull()
    })

    it('stores the Spoolman spool and refuses nonsense ids', async () => {
      const { id } = await createRequest(db, { title: 'Vase', spoolmanSpoolId: 17 }, USER)
      expect((await getRequest(db, id))?.spoolmanSpoolId).toBe(17)
      await updateRequest(db, id, { spoolmanSpoolId: null })
      expect((await getRequest(db, id))?.spoolmanSpoolId).toBeNull()
      await expect(updateRequest(db, id, { spoolmanSpoolId: 1.5 })).rejects.toThrow()
    })

    it('stores colour names and edits estimates', async () => {
      const { id } = await createRequest(
        db,
        { title: 'Vase', material: 'PLA', colorHex: '#112233', colorName: 'Galaxy Black' },
        USER,
      )
      await updateRequest(db, id, { estimatedMin: 125 })
      expect(await getRequest(db, id)).toMatchObject({
        colorName: 'Galaxy Black',
        estimatedMin: 125,
      })
      await expect(updateRequest(db, id, { estimatedMin: 0 })).rejects.toThrow()
    })
  })

  describe('on the printer', () => {
    it('records when it started, and gives the print history a real duration', async () => {
      const { id } = await createRequest(
        db,
        { title: 'Plate', modelId: SINGLE, colorName: 'Galaxy Black' },
        USER,
      )
      await setRequestStatus(db, id, 'printing')
      const started = (await getRequest(db, id))!.startedAt!
      expect(started).toBeInstanceOf(Date)

      // Pretend it went on the printer 50 minutes ago.
      await db.execute(sql`
        UPDATE print_requests SET started_at = started_at - interval '50 minutes' WHERE id = ${id}`)
      await setRequestStatus(db, id, 'done', { userId: USER })

      const [run] = await listPrints(db, { modelId: SINGLE })
      expect(run?.durationMin).toBe(50)
      expect(run?.colorName).toBe('Galaxy Black')

      // Reopened: the run the queue wrote — duration and all — is withdrawn.
      await setRequestStatus(db, id, 'requested')
      expect(await listPrints(db, { modelId: SINGLE })).toHaveLength(0)
      expect((await getRequest(db, id))?.startedAt).toBeNull()
    })

    it('clears the start time when it goes back to the queue', async () => {
      const { id } = await createRequest(db, { title: 'Plate' }, USER)
      await setRequestStatus(db, id, 'printing')
      await setRequestStatus(db, id, 'requested')
      expect((await getRequest(db, id))?.startedAt).toBeNull()
    })

    it('totals the time left in the queue', async () => {
      await createRequest(db, { title: 'A', estimatedMin: 30, quantity: 2 }, USER)
      await createRequest(db, { title: 'B' }, USER)
      const running = await createRequest(db, { title: 'C', estimatedMin: 120 }, USER)
      await setRequestStatus(db, running.id, 'printing')
      await db.execute(sql`
        UPDATE print_requests SET started_at = now() - interval '30 minutes'
        WHERE id = ${running.id}`)

      const stats = await queueStats(db)
      expect(stats.remainingMin).toBe(60 + 90)
      expect(stats.unestimated).toBe(1)
    })
  })
})
