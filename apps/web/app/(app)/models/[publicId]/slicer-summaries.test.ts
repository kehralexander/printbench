import { describe, expect, it } from 'vitest'
import { buildSlicerFileMeta, scanGcodeBody } from '@pb/core'
import { plateDetails, slicerSummary } from './slicer-summaries'

// The same small two-colour file as gcode-file-meta.test.ts.

const HEAD = `; generated by OrcaSlicer 2.1.1 on 2024-06-01 at 10:00:00
; model printing time: 50m; total estimated time: 1h 40m
; total layer number: 2
`

const TAIL = `
; filament used [g] = 3.0, 0.0, 1.5
; filament_type = PLA;PLA;PETG
; filament_colour = #FF0000;#00FF00;#0000FF
; filament_diameter = 1.75,1.75,1.75
; filament_density = 1.24,1.24,1.27
; layer_height = 0.2
; printable_area = 0x0,256x0,256x256,0x256
`

const BODY = `M83
M73 P0
T0
;LAYER_CHANGE
;Z:0.2
G1 X10 Y10 Z0.2
G1 X20 Y10 E1
M73 P50
T2
;TYPE:Prime tower
G1 X200 Y200 E10
;TYPE:Outer wall
M600
G1 X20 Y20 Z0.4 E1
`

describe('slicerSummary', () => {
  it('counts stops and tool changes only when the body was read', () => {
    const ends = slicerSummary(buildSlicerFileMeta(HEAD, TAIL, null))!
    expect(ends.stopCount).toBeNull()
    expect(ends.toolChanges).toBeNull()

    const full = slicerSummary(buildSlicerFileMeta(HEAD, TAIL, scanGcodeBody(BODY)))!
    expect(full.stopCount).toBe(1)
    expect(full.toolChanges).toBe(1)
    expect(full.stops).toEqual([
      { kind: 'filament_change', elapsedMin: 50, layer: 1, colorHex: null },
    ])
    expect(full).not.toHaveProperty('body')
  })

  it('is null without a read', () => {
    expect(slicerSummary(null)).toBeNull()
  })
})

describe('plateDetails', () => {
  it('places stops and tool changes on the timeline by the slicer’s clock', () => {
    const details = plateDetails(buildSlicerFileMeta(HEAD, TAIL, scanGcodeBody(BODY)))
    expect(details.timeline.bodyRead).toBe(true)
    expect(details.timeline.totalMin).toBe(100)
    expect(details.timeline.stops.map((stop) => stop.at)).toEqual([0.5])
    expect(details.timeline.toolChanges).toMatchObject([{ from: 0, to: 2, at: 0.5 }])
  })

  it('falls back to the layer when the file has no clock', () => {
    const body = BODY.replace(/M73.*\n/g, '').replace('M600', ';LAYER_CHANGE\n;Z:0.4\nM600')
    const details = plateDetails(buildSlicerFileMeta(HEAD, TAIL, scanGcodeBody(body)))
    // The start of layer 2 of 2.
    expect(details.timeline.stops[0]?.at).toBe(0.5)
  })

  it('joins purge to its tool and works out the waste', () => {
    const meta = buildSlicerFileMeta(HEAD, TAIL, scanGcodeBody(BODY))
    const details = plateDetails({ ...meta, filamentUsedG: 4.5 })
    expect(details.filaments.find((filament) => filament.tool === 2)?.purgeG).toBe(0.03)
    expect(details.filaments.find((filament) => filament.tool === 0)?.purgeG).toBeNull()
    expect(details.wastePercent).toBe(0.7)
    expect(details.geometry.bed).toEqual({ minX: 0, minY: 0, maxX: 256, maxY: 256 })
  })

  it('knows nothing of stops from the ends alone', () => {
    const details = plateDetails(buildSlicerFileMeta(HEAD, TAIL, null))
    expect(details.timeline).toMatchObject({ bodyRead: false, stopCount: 0, stops: [] })
  })
})
